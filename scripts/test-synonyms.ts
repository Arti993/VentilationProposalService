/**
 * Проверка словаря синонимов из обратной связи.
 *
 * Запуск: node --env-file=.env.local scripts/test-synonyms.ts
 *
 * ПОЧЕМУ ЭТОт МОДУЛЬ ТЕСТИРУЕТСЯ ОТДЕЛЬНО
 *
 * Замена подстроки — операция, которая выглядит простой и ломается на
 * краях: «ниппель» находится внутри «ниппельный», размер пишется слитно
 * с названием, а фразы разной длины перекрывают друг друга. Ошибка здесь
 * молчалива: строка просто перестанет находить цену, или, хуже, найдёт
 * чужую. Поэтому проверяем именно края, а не «счастливый путь».
 */

import {
  applySynonyms,
  buildSynonymTable,
  rewriteWithSynonym,
  type Synonym,
} from "../src/lib/matcher/synonyms.ts";

let passed = 0;
let failed = 0;

function ok(name: string, detail = ""): void {
  passed += 1;
  console.log(`  ✓ ${name}${detail ? ` — ${detail}` : ""}`);
}

function fail(name: string, detail: string): void {
  failed += 1;
  console.log(`  ✗ ${name} — ${detail}`);
}

function check(name: string, actual: unknown, expected: unknown): void {
  const a = JSON.stringify(actual);
  const e = JSON.stringify(expected);
  if (a === e) ok(name);
  else fail(name, `получили ${a}, ожидали ${e}`);
}

// ── 1. Сборка словаря ─────────────────────────────────────

console.log("\n=== Сборка словаря ===");

{
  const table = buildSynonymTable([
    { rawText: "Воздуховод спиральный", code: "p015" },
    { rawText: "  ниппель  ", code: "p020" },
  ]);
  check("фразы в нижнем регистре", [...table.byPhrase.keys()].sort(), [
    "воздуховод спиральный",
    "ниппель",
  ]);
  check("лишние пробелы убраны", table.byPhrase.get("ниппель"), "p020");
}

{
  // Слишком короткие фразы опасны: «ф» есть почти в каждой строке
  const table = buildSynonymTable([
    { rawText: "ф", code: "p001" },
    { rawText: "д", code: "p002" },
    { rawText: "отв", code: "p003" },
  ]);
  check("короткие (< 3 символов) отброшены", table.byPhrase.size, 0);
}

{
  /**
   * Одна формулировка, два разных кода — это КОНФЛИКТ, а не «берём
   * первый».
   *
   * Раньше здесь стояло «первый код выигрывает»: результат не зависел от
   * порядка строк в базе, и на этом успокаивались. Но менеджер, чей разбор
   * пришёл вторым, видел свой ответ сохранённым и не понимал, почему
   * система его не применяет.
   *
   * Теперь такая фраза исключается из словаря, а конфликт возвращается
   * наружу — вызывающий код логирует его, и расхождение видно людям.
   * Строка пойдёт обычным путём (матчинг → RAG/LLM → человек), и цена не
   * будет поставлена по спорному правилу.
   */
  const table = buildSynonymTable([
    { rawText: "переход", code: "p100" },
    { rawText: "переход", code: "p200" },
  ]);
  check("конфликт: формулировка не в словаре", table.byPhrase.has("переход"), false);
  check("конфликт: коды перечислены", table.conflicts[0]?.codes.join(","), "p100,p200");
}

{
  // Одинаковый код по одной фразе из разных смет — не конфликт: менеджеры
  // в разных ситуациях подтвердили одно и то же, это усиление, а не спор
  const table = buildSynonymTable([
    { rawText: "переход", code: "p100" },
    { rawText: "переход", code: "p100" },
  ]);
  check("дубль с тем же кодом применяется", table.byPhrase.get("переход"), "p100");
  check("и конфликтом не считается", table.conflicts.length, 0);
}

{
  const table = buildSynonymTable([]);
  check("пустой словарь — пустая карта", table.byPhrase.size, 0);
  check("пустой словарь ничего не меняет", applySynonyms("Тройник 315/200", table), {
    text: "Тройник 315/200",
    code: null,
  });
}

// ── 2. Границы совпадения ─────────────────────────────────

console.log("\n=== Границы совпадения ===");

const base = buildSynonymTable([
  { rawText: "воздуховод спиральный", code: "p015" },
  { rawText: "воздуховод", code: "p010" },
  { rawText: "ниппель", code: "p020" },
]);

{
  const r = applySynonyms("Воздуховод спиральный 315", base);
  check("длинная фраза важнее короткой", r.code, "p015");
}

{
  const r = applySynonyms("Воздуховод 315", base);
  check("короткая фраза тоже находится", r.code, "p010");
}

{
  // Главный случай ложного срабатывания: «ниппельный» — другое слово
  const r = applySynonyms("Ниппельный переход 315/200", base);
  check("«ниппель» НЕ срабатывает внутри «ниппельный»", r.code, null);
}

{
  const r = applySynonyms("Купить ниппель 250", base);
  check("совпадение в середине строки", r.code, "p020");
}

{
  // Размер пишется слитно — после фразы сразу цифра
  const r = applySynonyms("ниппель250", base);
  check("после фразы сразу цифра", r.code, "p020");
}

{
  const r = applySynonyms("тройник 315/200", base);
  check("незнакомая формулировка → null", r.code, null);
}

{
  // Регистр не важен: клиенты пишут как угодно
  const r = applySynonyms("ВОЗДУХОВОД СПИРАЛЬНЫЙ 400", base);
  check("верхний регистр распознаётся", r.code, "p015");
}

// ── 3. Переписывание строки ───────────────────────────────

console.log("\n=== Переписывание строки ===");

const priceNames = new Map([
  ["p015", "Воздуховод спирально-навивной 315"],
  ["p010", "Воздуховод круглый 315"],
  ["p020", "Ниппель круглый 250"],
]);

{
  const r = rewriteWithSynonym("Воздуховод спиральный 315, 10 м", base, priceNames);
  check(
    "формулировка заменена на название из прайса",
    r.text,
    "Воздуховод спирально-навивной 315 315, 10 м",
  );
  check("код позиции возвращён", r.code, "p015");
}

{
  // Количество и единица должны остаться: иначе сломается разбор qty
  const r = rewriteWithSynonym("ниппель250, 4 шт", base, priceNames);
  check("количество сохранено", r.text, "Ниппель круглый 250250, 4 шт");
}

{
  // Позицию из прайса убрали, а синоним остался — строку не трогаем
  const r = rewriteWithSynonym("Воздуховод 315", base, new Map());
  check("нет позиции в прайсе → строка не меняется", r.text, "Воздуховод 315");
  check("и код не подсказывается", r.code, null);
}

{
  const r = rewriteWithSynonym("Тройник 315/200", base, priceNames);
  check("незнакомая строка не меняется", r.text, "Тройник 315/200");
}

// ── 4. Порядок фраз при замене ────────────────────────────

console.log("\n=== Порядок фраз ===");

{
  // Короткий синоним не должен переписать строку раньше длинного:
  // иначе «воздуховод» заменит начало, и «спиральный» останется висеть
  const table = buildSynonymTable([
    { rawText: "воздуховод", code: "p010" },
    { rawText: "воздуховод спиральный", code: "p015" },
  ]);
  const names = new Map([
    ["p010", "ВК"],
    ["p015", "ВС"],
  ]);
  const r = rewriteWithSynonym("воздуховод спиральный 315", table, names);
  check("длинная фраза заменяется первой", r.text, "ВС 315");
}

// ── 5. Дублирование размера ───────────────────────────────
//
// Найдено сквозным тестом: строка «Воздуховод спиральный 315» после
// замены превращалась в «Воздуховод спирально-навивной 315, м.п. 315».
// Размер оказывался дважды, и разбор количества принимал второй «315» за
// количество — то есть в смете появлялось «315 штук».

console.log("\n=== Дублирование размера ===");

{
  const table = buildSynonymTable([{ rawText: "воздуховод спиральный", code: "p015" }]);
  const names = new Map([["p015", "Воздуховод спирально-навивной 315"]]);
  const dims = new Map([["p015", [315]]]);

  const r = rewriteWithSynonym("Воздуховод спиральный 315; 10; м.п.", table, names, dims);
  check("размер не дублируется", r.text, "Воздуховод спирально-навивной 315; 10; м.п.");
}

{
  /**
   * Размер позиции отличается от того, что написал клиент.
   *
   * Менеджер мог сопоставить строку «спиральный 315» с позицией «400» —
   * например, понял, что клиент имел в виду другой типоразмер. Название
   * позиции «400» убирать НЕЛЬЗЯ: это размер самой позиции, и без него
   * название станет неверным. «315» из строки остаётся рядом, потому что
   * вырезать чужие числа из названия опасно.
   *
   * Ожидание зафиксировано по фактическому правильному поведению: лучше
   * лишний размер, чем потерянный.
   */
  const table = buildSynonymTable([{ rawText: "воздуховод спиральный", code: "p015" }]);
  const names = new Map([["p015", "Воздуховод спирально-навивной 400"]]);
  const dims = new Map([["p015", [400]]]);

  const r = rewriteWithSynonym("Воздуховод спиральный 315", table, names, dims);
  check("размер позиции не теряется", r.text, "Воздуховод спирально-навивной 400 315");
}

{
  // Без карты размеров поведение прежнее: название берётся как есть.
  // Это обратная совместимость — старые вызовы не должны падать.
  const table = buildSynonymTable([{ rawText: "ниппель стандарт", code: "p020" }]);
  const names = new Map([["p020", "Ниппель круглый 250"]]);
  const r = rewriteWithSynonym("ниппель стандарт 250", table, names);
  check("без размеров — прежнее поведение", r.text, "Ниппель круглый 250 250");
}

// ── Итог ──────────────────────────────────────────────────

console.log(`\n═══ Итог: ${passed} из ${passed + failed} проверок пройдено ═══`);
process.exit(failed === 0 ? 0 : 1);
