-- Сведения о загруженном прайсе организации.
--
-- ЗАЧЕМ
--
-- По позициям нельзя ответить на «какой файл загружен и когда». Без этого
-- кабинет не может показать «прайс: прайс_2026.xlsx, 215 позиций», а
-- главный экран — отличить «своего прайса ещё нет» от «есть, но пустой».
--
-- Разница принципиальная: в первом случае расчёт идёт по демо-прайсу, и
-- об этом надо сказать вслух. Во втором человек загрузил файл, из
-- которого ничего не разобралось, — и это другая просьба о помощи.
--
-- Одна строка на организацию: замена прайса перезаписывает её. История
-- версий не нужна ни одному экрану.
--
-- Применяется скриптом scripts/apply-migration-0008.ts. Все шаги
-- идемпотентны: повторный запуск ничего не меняет.

create table if not exists price_meta (
  org_id      text primary key,
  file_name   text not null,
  item_count  integer not null,
  uploaded_at timestamptz not null default now()
);

-- Ссылка на организацию с каскадом.
--
-- Сначала её не было: казалось, что жёсткая ссылка создаст проблему
-- порядка «сначала организация, потом прайс». Оказалось наоборот: без неё
-- за удалённой организацией остаётся строка с именем файла — мусор,
-- который никто никогда не прочитает и не заметит.
--
-- Нашлось на уборке тестов: после прогонов в таблице висели строки
-- организаций, которых уже нет в базе.
--
-- Загрузка прайса происходит заведомо позже создания организации, так что
-- порядок здесь ничем не рискует.
alter table price_meta
  drop constraint if exists price_meta_org_fk;

alter table price_meta
  add constraint price_meta_org_fk
  foreign key (org_id) references organization(id) on delete cascade;