-- Время разбора сметы в миллисекундах.
--
-- ЗАЧЕМ
--
-- Страница /status показывает «медиана обработки сметы». Без этой колонки
-- её приходилось считать как разницу между created_at и notified_at — то
-- есть время до того, как смету забрал n8n. На практике это десятки
-- минут, и метрика показывала бы «67 минут» вместо реальных трёх секунд.
--
-- Метрика, которая врёт в двадцать раз, хуже отсутствующей метрики:
-- на неё смотрят и делают выводы.
--
-- Колонка nullable: у ста смет, созданных до её появления, времени нет.
-- Медиана считается по тем, у кого оно есть, и это честно — лучше меньше
-- данных, чем подставленные нули.
--
-- Применяется скриптом scripts/apply-migration-0007.ts.

alter table estimates
  add column if not exists parse_ms integer;

