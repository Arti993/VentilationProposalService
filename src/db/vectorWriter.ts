/**
 * Запись векторов в `price_items`.
 *
 * ИСТОРИЯ ВОПРОСА (важна: без неё первое же «упрощение» всё сломает)
 *
 * Запись вектора через `postgres.js` на этой базе обрывается: и
 * `insert … values (…, $1::vector)`, и `update … set embedding = …` висят
 * 19-25 секунд и падают с `write CONNECTION_CLOSED` / `read ECONNRESET`.
 * Воспроизводимость — 3 из 3, стабильно, независимо от размера таблицы,
 * индексов и состояния соединения.
 *
 * Причина найдена замером: дело в РАЗМЕРЕ текстового параметра. Вектор из
 * 1024 чисел, сериализованный «как есть» (`JSON.stringify` чисел с полной
 * точностью `f64`), — это 21 682 байта. Порог проверен по шагам:
 *
 *   4097 байт   (1024 значения по 1 знаку)   → 35 мс, ок
 *   8193 байта  (по 5 знаков)                → 36 мс, ок
 *   13 313 байт (по 10 знаков)               → обрыв через 19 с
 *   21 682 байта (реальный вектор)           → обрыв через 19 с
 *
 * То есть пулер Neon не пропускает одиночный параметр крупнее примерно
 * 8-13 КБ: соединение закрывается посреди запроса. Ни `statement_timeout`,
 * ни `idle_timeout`, ни размер батча тут ни при чём — это проверено
 * отдельно.
 *
 * РЕШЕНИЕ: округление.
 *
 * Вектор `bge-m3` нормализован, значения лежат примерно в диапазоне
 * -0.15…0.20. Пять знаков после запятой дают абсолютную погрешность
 * ≤ 5e-6 на компоненту, а длина вектора при этом остаётся равной 1 с
 * точностью до 1e-5 — на косинусное расстояние это влияет в шестом знаке,
 * то есть на порядки меньше, чем разница между «похоже» и «не похоже».
 *
 * Выигрыш по размеру: `0.014531522057950497` (20 символов) превращается в
 * `0.01453` (7 символов) — вся строка сжимается с 21 682 до ~8600 байт,
 * ниже порога пулера. Проверено: 3 из 3 векторов записываются за 247-276 мс.
 *
 * Что НЕ работает (проверено, чтобы не повторять):
 *  - hex-упаковка `float4` (8192 символа) — параметр мал, но распаковка
 *    обратно в SQL через `get_byte`/`generate_series` на 1024 элементах
 *    упирается в таймаут 60 с. Сборка из четырёх частей по 256 — то же.
 *  - `insert … on conflict do update` — та же проблема размера параметра.
 *  - отдельный драйвер `pg` — помогает, но само по себе не спасает:
 *    реальный вектор 21 КБ рвётся и там. Размер важен, драйвер — нет.
 *
 * ПОЧЕМУ `pg`, А НЕ `postgres.js`
 *
 * Работает оба, но на `pg` приём проверен с первого раза, и он же
 * используется для чтения остатка индексации. Обычные запросы приложения
 * остаются на `postgres.js` (см. `connection.ts`): там всё в порядке, и
 * переезд всего слоя данных был бы отдельной большой задачей.
 */

import pg from "pg";

const { Client } = pg;

/** Сколько ждать подключения и одного запроса, мс. */
const CONNECT_TIMEOUT_MS = 15_000;
const QUERY_TIMEOUT_MS = 20_000;

/**
 * Знаков после запятой при упаковке вектора.
 *
 * 5 — проверенный компромисс: строка ~8.6 КБ проходит порог пулера с
 * запасом, а точность косинуса страдает в шестом знаке. Увеличивать до 6
 * рискованно (9612 байт — вплотную к порогу), уменьшать до 4 смысла нет.
 */
const VECTOR_PRECISION = 5;

function clientOptions() {
  const connectionString = process.env.DATABASE_URL;
  if (!connectionString) {
    throw new Error("DATABASE_URL не задан — некуда писать векторы");
  }
  return {
    connectionString,
    ssl: { rejectUnauthorized: false },
    connectionTimeoutMillis: CONNECT_TIMEOUT_MS,
    query_timeout: QUERY_TIMEOUT_MS,
  };
}

/**
 * Сериализует вектор компактно, округляя компоненты.
 *
 * `Math.round(x * 1e5) / 1e5` вместо голого числа — это и есть та
 * экономия, которая проходит порог пулера. Менять точность без замера
 * нельзя: на 6 знаках строка уже 9612 байт, и запас кончается.
 */
function packVector(vector: number[]): string {
  const factor = 10 ** VECTOR_PRECISION;
  const rounded = vector.map((x) => Math.round(x * factor) / factor);
  return JSON.stringify(rounded);
}

export interface VectorRow {
  /** Код позиции внутри организации — по нему находим строку. */
  code: string;
  /** Вектор размерностью 1024 (см. `EMBED_DIM`). */
  vector: number[];
}

/**
 * Записывает векторы, по одному `update` на позицию.
 *
 * Каждая запись — в своём соединении. Это стоит ~260 мс на позицию, но
 * именно так запись проходит: переиспользование соединения после
 * векторной записи почти сразу ловит `ECONNRESET` (проверено — второй
 * запрос на том же клиенте падает через 19 с даже после успешного
 * первого). Индексация идёт в фоне после ответа клиенту и пачками по
 * `MAX_PER_RUN`, так что цена приемлема.
 */
export async function writeVectors(
  orgId: string,
  rows: VectorRow[],
): Promise<{ written: number; failed: { code: string; error: string }[] }> {
  if (rows.length === 0) return { written: 0, failed: [] };

  let written = 0;
  const failed: { code: string; error: string }[] = [];

  for (const row of rows) {
    const client = new Client(clientOptions());
    /**
     * `pg` вешает ошибки соединения на событие `error`. Без обработчика
     * `ECONNRESET` превращается в необработанное исключение и роняет
     * процесс, а нам нужно просто перейти к следующей позиции.
     */
    client.on("error", () => {});

    try {
      await client.connect();
      /**
       * `update`, а не `insert … on conflict`: строка уже существует, её
       * создала загрузка прайса. Условие `embedding is null` страхует от
       * повторной работы, если позицию уже проиндексировали.
       */
      const result = await client.query(
        `update price_items
            set embedding = $3::vector,
                embedded_at = now()
          where org_id = $1
            and code = $2
            and embedding is null`,
        [orgId, row.code, packVector(row.vector)],
      );
      if (result.rowCount && result.rowCount > 0) written += 1;
    } catch (e) {
      failed.push({
        code: row.code,
        error: e instanceof Error ? e.message : String(e),
      });
    } finally {
      /**
       * `end()` НЕ ждём.
       *
       * Замерено: закрытие соединения `pg` к этому пулеру висит около
       * 70 секунд — сервер не отвечает на `Terminate`, и `end()` ждёт
       * ответа до своего внутреннего таймаута. Две позиции превращались в
       * 139 секунд при 260 мс собственно записи.
       *
       * Соединение нам больше не нужно, его закрытие — забота пулера и
       * сборщика мусора. Запускаем и идём дальше: ошибки внутри `end()`
       * гасится обработчиком `error`, который мы повесили при создании
       * клиента.
       */
      void client.end().catch(() => {});
    }
  }

  return { written, failed };
}

/**
 * Сколько позиций организации ещё без вектора.
 *
 * Отдельная функция и отдельное соединение: читать через `postgres.js`
 * можно, но тогда остаток считается в одном месте, а запись идёт в
 * другом — и расхождение типов соединений уже дважды стоило нам
 * неверных диагнозов.
 */
export async function countUnindexed(orgId: string): Promise<number> {
  const client = new Client(clientOptions());
  client.on("error", () => {});
  try {
    await client.connect();
    const result = await client.query<{ n: number }>(
      `select count(*)::int as n from price_items
        where org_id = $1 and embedding is null`,
      [orgId],
    );
    return result.rows[0]?.n ?? 0;
  } finally {
    await client.end().catch(() => {});
  }
}
