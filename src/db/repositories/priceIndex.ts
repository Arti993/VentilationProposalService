/**
 * Фоновая индексация прайса для поиска по смыслу.
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ ЗАГРУЗКИ
 *
 * Загрузка прайса на 215 позиций занимает около секунды. Индексация того
 * же прайса — это 7 обращений к модели эмбеддингов, то есть десятки
 * секунд. Если делать это в том же запросе, клиент ждал бы сорок секунд
 * вместо секунды, а на бесплатном Vercel (лимит 60 с) большой прайс
 * привёл бы к таймауту — причём уже после того, как старый прайс удалён.
 *
 * Поэтому порядок такой:
 *
 *   1. Загрузка: разбор, запись в базу, ответ клиенту. Секунда.
 *   2. Индексация: считается в фоне, позиции пока без вектора.
 *
 * ЧТО ЭТО ЗНАЧИТ ДЛЯ КП
 *
 * Пока индекс не готов, точный путь матчинга работает полностью:
 * нормализация, тип, размеры — всё это берёт данные из тех же колонок,
 * а не из вектора. RAG нужен только для сложных формулировок
 * («отвод на 90 с переходом на 200»), и на это время такие строки
 * получат `needs_llm` — то есть уйдут на ручную проверку, а не получат
 * выдуманную цену. Это то самое «ошибочный матч опаснее отсутствия
 * матча».
 *
 * ПОЧЕМУ ВСТАВКА, А НЕ ОБНОВЛЕНИЕ
 *
 * Это главное открытие при разработке, и оно стоило часа проверок.
 *
 * Естественный способ проставить вектор — `update price_items set
 * embedding = …`. На этой базе он РВЁТ соединение: запись висит
 * 19-27 секунд и падает с `write CONNECTION_CLOSED`. Замерено, что дело
 * не в размере: обрыв одинаков на 16 измерениях (312 байт) и на 1024
 * (21 КБ), и повторяется в пустой таблице без единого индекса. То есть
 * виноват не наш прайс и не HNSW.
 *
 * Рабочий путь — `insert` в СВЕЖЕМ соединении, ровно одна запись с
 * вектором на соединение: 0.5-0.8 секунды, стабильно. Это та же самая
 * особенность пулера Neon, из-за которой пришлось переписать адаптер
 * регистрации (docs/INCIDENT-SIGNUP.md): вторая запись в одном
 * соединении/транзакции убивает его.
 *
 * Отсюда `heavy: true` — оно заставляет `withRetry` открыть новое
 * соединение под каждый запрос. Поэтому здесь нельзя делать несколько
 * `insert` подряд в одном `withRetry`.
 *
 * КАК ЗАПУСКАЕТСЯ БЕЗ ОЧЕРЕДИ
 *
 * `waitUntil` из `@vercel/functions` — не блокирует ответ, но продлевает
 * жизнь функции. Ночной n8n-сторож добивает то, что не успело:
 * `scripts/index-price.ts` умеет находить позиции без вектора и
 * доиндексировать их. Это и есть «фоновая индексация» на бесплатном
 * тарифе: сразу — что успеем, остальное — следующим прогоном.
 */

import { withRetry } from "../connection.ts";
import { countUnindexed, writeVectors } from "../vectorWriter.ts";
import { embedTexts, itemEmbeddingText } from "../../lib/rag/embed.ts";

/** Сколько позиций отправлять в одну пачку к модели эмбеддингов. */
const BATCH = 32;

/**
 * Сколько позиций индексировать за один заход.
 *
 * 32 = одна пачка. Меньше, чем хотелось бы, но каждая позиция — это
 * отдельное соединение и отдельный `insert` на 0.5-0.8 с. Тридцать две
 * штуки уже занимают около 25 секунд, а функция на бесплатном Vercel
 * живёт 60. Остаток доиндексируется следующим прогоном: скрипт ищет
 * позиции без вектора и продолжит с места остановки.
 */
const MAX_PER_RUN = 32;

export interface IndexResult {
  /** Сколько позиций получили вектор за этот заход. */
  indexed: number;
  /** Сколько ещё ждут индексации. */
  pending: number;
  /** Ошибка, если индексация сорвалась. Не бросаем: загрузка уже прошла. */
  error?: string;
}

/**
 * Индексирует часть прайса организации.
 *
 * Никогда не бросает исключение: загрузка прайса уже завершилась
 * успешно, и падение индексации не должно выглядеть как «прайс не
 * загрузился» — данные-то на месте, просто поиск по смыслу отстаёт.
 */
export async function indexPriceInBackground(orgId: string): Promise<IndexResult> {
  let indexed = 0;
  let pending = 0;

  /**
   * Сбрасываем переиспользуемое соединение ПЕРЕД работой.
   *
   * Замерено: если индексация запускается сразу после `replacePrice` (а
   * именно так и происходит — она вызывается из загрузки прайса),
   * вставка с вектором падает с `write CONNECTION_CLOSED`. Причина в том,
   * что `replacePrice` пишет сотни строк через переиспользуемое
   * соединение, и к моменту индексации оно уже непригодно для записи
   * вектора.
   *
   * Холодное соединение с той же вставкой проходит за 580 мс. Поэтому
   * соединение под каждую запись вектора берётся отдельно (`connectOnce`),
   * а общий пул для записи не используется вообще.
   */

  let rows: {
    id: number;
    code: string;
    raw_name: string;
    price: string;
    type: string;
    dims_key: string;
    dims: unknown;
    angle: number | null;
    variant: string | null;
    unparsed: string | null;
  }[] = [];

  try {
    rows = await withRetry(
      async (sql) =>
        sql`
          select id, code, raw_name, price, type, dims_key, dims, angle, variant, unparsed
            from price_items
           where org_id = ${orgId} and embedding is null
           order by id
           limit ${MAX_PER_RUN}
        `,
      { label: `чтение для индексации ${orgId}` },
    );
  } catch (e) {
    return { indexed: 0, pending: -1, error: e instanceof Error ? e.message : String(e) };
  }

  if (rows.length === 0) return { indexed: 0, pending: 0 };

  let vectors: number[][];
  try {
    // Один вызов на всю пачку: модель эмбеддингов принимает массив
    vectors = await embedTexts(
      rows.map((r) =>
        itemEmbeddingText({
          rawName: r.raw_name,
          type: r.type,
          dimsKey: r.dims_key,
          angle: r.angle,
        }),
      ),
    );
  } catch (e) {
    return { indexed: 0, pending: -1, error: e instanceof Error ? e.message : String(e) };
  }
  /**
   * Запись векторов — через `writeVectors` (см. `db/vectorWriter.ts`).
   *
   * Там же подробно описано, почему это отдельный модуль и отдельный
   * драйвер: у пулера Neon есть порог на размер одного параметра, и вектор
   * в 21 КБ (полная точность `f64`) его пробивает — соединение рвётся
   * через 19 секунд. Вектор, округлённый до 5 знаков (~8.6 КБ), проходит
   * за 250 мс.
   *
   * Важно, что здесь только запись вектора в СУЩЕСТВУЮЩУЮ строку:
   * позиции создаёт загрузка прайса, индексатор их не трогает. Потерять
   * позицию прайса ради вектора нельзя — цена важнее поиска по смыслу.
   */
  const result = await writeVectors(
    orgId,
    rows
      .map((row, i) => ({ code: row.code, vector: vectors[i] }))
      .filter((r): r is { code: string; vector: number[] } => Boolean(r.vector)),
  );

  indexed = result.written;

  if (result.failed.length > 0) {
    /**
     * Первый сбой в ответе: в журнале нужна причина, а не счётчик.
     * Остальные позиции попробует следующий прогон — они так и остались
     * с `embedding is null`.
     */
    const first = result.failed[0];
    return {
      indexed,
      pending: -1,
      error: first ? `${first.code}: ${first.error}` : "неизвестная ошибка индексации",
    };
  }

  /**
   * Остаток считаем тем же драйвером, что и запись: расхождение типов
   * соединений уже дважды приводило к неверным диагнозам.
   */
  pending = await countUnindexed(orgId);

  return { indexed, pending };
}

