/**
 * Тестовые сметы клиентов — с ловушками, собранными под РЕАЛЬНЫЙ прайс.
 *
 * Каждая строка проверяет конкретный риск:
 *  - искажение написания (d315 / Ø315 / 315 мм / ф-315)
 *  - размер есть у одного типа, но не у другого (отвод 450 нет, прямая 450 есть)
 *  - вариант исполнения (R / без R)
 *  - пометка "(круглая)" в прайсе
 *  - мусор/оффтоп, который не должен превращаться в цену
 */
export interface TestCase {
  /** Строка, которую "прислал клиент" */
  line: string;
  /** Ожидаемый статус */
  expected: "matched" | "ambiguous" | "not_found" | "needs_llm";
  /** Ожидаемая цена за единицу, если matched */
  expectedPrice?: number;
  /** Что проверяет */
  why: string;
}

