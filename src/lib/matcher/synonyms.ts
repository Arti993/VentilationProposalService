/**
 * Словарь синонимов организации, собранный из обратной связи менеджера.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫЙ МОДУЛЬ
 *
 * `matchLine` — чистая функция: строка и прайс на входе, результат на
 * выходе. Это её главное достоинство: её можно проверить без базы и без
 * модели, и она никогда не «зависает» от сетевой ошибки. Подмешать в неё
 * чтение из БД значило бы потерять это свойство.
 *
 * Поэтому синонимы применяются СНАРУЖИ: строка сметы переписывается перед
 * матчингом, а `matchLine` продолжает работать как раньше. Если словарь
 * пуст или база недоступна — ничего не меняется, и это правильно:
 * дополнительный словарь должен улучшать, а не быть обязательным.
 *
 * ЧТО СЧИТАЕТСЯ СИНОНИМОМ
 *
 * Пара «как написал клиент → код позиции прайса», подтверждённая
 * менеджером (статус `applied`). Правило применения нарочно узкое:
 *
 * - заменяем только вхождение исходной формулировки в начало строки или
 *   в её середину, не трогая цифры и окончания;
 * - заменяем на `raw_name` позиции из прайса, то есть на ту
 *   формулировку, которую `matchLine` уже понимает.
 *
 * Узость здесь принципиальная. Широкая замена («слово похоже — меняем»)
 * на прайсе в 215 позиций даёт ложные попадания: «переход» и «переход
 * сэндвич» это разные изделия с разной ценой. Ошибочный матч опаснее
 * отсутствия матча, и словарь не повод делать исключение.
 */

export interface Synonym {
  /** Как написал клиент */
  rawText: string;
  /** Код позиции прайса, которую выбрал менеджер */
  code: string;
}

export interface SynonymTable {
  /** Исходная формулировка (в нижнем регистре) → код позиции */
  byPhrase: Map<string, string>;
  /** Длина самой длинной фразы: чтобы не перебирать заведомо длинные */
  maxLength: number;
  /**
   * Формулировки, по которым менеджеры подтвердили РАЗНЫЕ коды.
   *
   * Такие фразы в словарь не попадают: если один менеджер сказал «это
   * p065», а другой «это p066», то непонятно, кто прав, и переписывать
   * строку по одному из них — значит ставить цену наугад.
   *
   * Конфликт не молчит: он возвращается наружу, чтобы попасть в лог или
   * в интерфейс. Раньше «первое подтверждение выигрывало», и второй
   * разбор просто терялся — менеджер видел свой ответ сохранённым, а
   * система его игнорировала.
   */
  conflicts: { phrase: string; codes: string[] }[];
}

/**
 * Собирает словарь для применения.
 *
 * МИНИМАЛЬНАЯ ДЛИНА — 4 СИМВОЛА, И ЭТО ПО ЗАМЕРУ.
 *
 * Первая версия отбрасывала фразы короче трёх, и тест сразу показал, что
 * «отв» (три символа) проходит порог. А «отв» — это стандартное
 * сокращение от «отвод» в сметах: приняв его за синоним к конкретной
 * позиции, мы переписали бы ЛЮБОЙ отвод в один и тот же код, независимо
 * от типа и размеров. То же с «ф» (диаметр), «д» (длина), «шт».
 *
 * Порог 4 отсекает самые опасные сокращения, оставляя нормальные слова:
 * «муфта», «заглушка», «отвод» — все длиннее. Остаток риска закрывает
 * проверка границ ниже.
 */
const MIN_PHRASE_LENGTH = 4;

export function buildSynonymTable(synonyms: Synonym[]): SynonymTable {
  const byPhrase = new Map<string, string>();
  /**
   * Все коды по формулировке — чтобы поймать противоречие.
   *
   * Нужен отдельный список, а не проверка `byPhrase.get(phrase) !== code`:
   * формулировка могла встретиться дважды с ОДИНАКОВЫМ кодом (менеджеры
   * в разных сметах подтвердили одно и то же), и это не конфликт.
   */
  const codesByPhrase = new Map<string, Set<string>>();
  const conflicts: { phrase: string; codes: string[] }[] = [];
  let maxLength = 0;

  for (const s of synonyms) {
    const phrase = s.rawText.trim().toLowerCase().replace(/\s+/g, " ");
    if (phrase.length < MIN_PHRASE_LENGTH) continue;

    let codes = codesByPhrase.get(phrase);
    if (!codes) {
      codes = new Set();
      codesByPhrase.set(phrase, codes);
    }
    codes.add(s.code);

    maxLength = Math.max(maxLength, phrase.length);
  }

  for (const [phrase, codes] of codesByPhrase) {
    if (codes.size === 1) {
      // Обычный случай: формулировка однозначно ведёт к одной позиции
      byPhrase.set(phrase, [...codes][0]);
      continue;
    }

    /**
     * Конфликт: разные менеджеры выбрали разные позиции.
     *
     * Не выбираем «первый попавшийся» — вместо этого фразу исключаем из
     * словаря. Строка тогда пойдёт обычным путём (матчинг, затем
     * RAG/LLM, затем человек), и цена не будет поставлена по спорному
     * правилу. Ошибка станет видна в `conflicts`, а не спрячется.
     */
    conflicts.push({ phrase, codes: [...codes].sort() });
  }

  return { byPhrase, maxLength, conflicts };
}

/**
 * Переписывает строку сметы по словарю.
 *
 * Возвращает и переписанный текст, и код, который словарь подсказал: если
 * подсказка есть, вызывающий код может использовать её как сильный сигнал
 * и не звать модель. `null` — словарь ничего не знает про эту строку.
 *
 * ПОЧЕМУ НЕ ЗАМЕНА ПОДСТРОКИ БЕЗ ГРАНИЦ
 *
 * `indexOf` без проверки границ найдёт «ниппель» внутри «ниппельный».
 * Для русского языка с его окончаниями это массовый ложный сигнал,
 * поэтому проверяем, что перед совпадением стоит начало строки или
 * пробел, а после — конец строки, пробел или цифра (цифра нужна: размер
 * часто пишется слитно — «переход 315/200»).
 */
export function applySynonyms(
  line: string,
  table: SynonymTable,
): { text: string; code: string | null } {
  if (table.byPhrase.size === 0) return { text: line, code: null };

  const lower = line.toLowerCase();
  // Идём от длинных фраз к коротким: иначе «воздуховод» перепишется
  // раньше, чем «воздуховод спиральный», и второй синоним уже не найдётся.
  const phrases = [...table.byPhrase.keys()].sort((a, b) => b.length - a.length);

  for (const phrase of phrases) {
    let from = 0;
    for (;;) {
      const at = lower.indexOf(phrase, from);
      if (at === -1) break;

      const beforeOk = at === 0 || /\s/.test(lower[at - 1]);
      const afterIdx = at + phrase.length;
      const afterOk =
        afterIdx >= lower.length || /[\s\d,./)]/.test(lower[afterIdx]);

      if (beforeOk && afterOk) {
        return { text: line, code: table.byPhrase.get(phrase) ?? null };
      }
      from = at + 1;
    }
  }

  return { text: line, code: null };
}

/**
 * Заменяет формулировку в строке на `raw_name` позиции прайса.
 *
 * Отдельно от `applySynonyms`: сначала надо узнать код, потом найти
 * позицию в прайсе и взять её название. Разделение позволяет вызывающему
 * коду решать, что делать, если позиции с таким кодом уже нет (прайс
 * перезаписали) — в этом случае строка остаётся как есть, а синоним
 * считается устаревшим.
 *
 * ПОЧЕМУ НАЗВАНИЕ ЧИСТИТСЯ ОТ РАЗМЕРА
 *
 * Названия в прайсе часто уже содержат размер: «Воздуховод
 * спирально-навивной 315». А строка сметы — тоже: «Воздуховод спиральный
 * 315». При простой замене получается «Воздуховод спирально-навивной 315
 * 315»: размер дублируется, и разбор количества принимает второй «315» за
 * количество.
 *
 * Поэтому размер, который уже есть в строке, из названия убираем. Размер
 * восстанавливается из `dims` позиции, а не вырезается регуляркой наугад:
 * «315» может быть и частью названия, и диаметром, и толщиной.
 */
export function rewriteWithSynonym(
  line: string,
  table: SynonymTable,
  priceNames: Map<string, string>,
  /** Размеры позиции — чтобы убрать их дублирование из названия */
  priceDims?: Map<string, number[]>,
): { text: string; code: string | null } {
  const { code } = applySynonyms(line, table);
  if (!code) return { text: line, code: null };

  const rawTarget = priceNames.get(code);
  if (!rawTarget) return { text: line, code: null };

  const target = stripDuplicateDims(rawTarget, line, priceDims?.get(code) ?? []);

  // Находим ту же фразу, которую распознал applySynonyms, и меняем только
  // её: остальная часть строки (количество, единица измерения) должна
  // остаться нетронутой, иначе сломается разбор количества.
  const lower = line.toLowerCase();
  const phrases = [...table.byPhrase.keys()].sort((a, b) => b.length - a.length);

  for (const phrase of phrases) {
    if (table.byPhrase.get(phrase) !== code) continue;

    let from = 0;
    for (;;) {
      const at = lower.indexOf(phrase, from);
      if (at === -1) break;

      const beforeOk = at === 0 || /\s/.test(lower[at - 1]);
      const afterIdx = at + phrase.length;
      const afterOk =
        afterIdx >= lower.length || /[\s\d,./)]/.test(lower[afterIdx]);

      if (beforeOk && afterOk) {
        return {
          text: line.slice(0, at) + target + line.slice(at + phrase.length),
          code,
        };
      }
      from = at + 1;
    }
  }

  return { text: line, code: null };
}

/**
 * Убирает из названия позиции размер, который уже есть в строке сметы.
 *
 * ОТКУДА ЭТО ВЗЯЛОСЬ
 *
 * Сквозной тест показал: строка «Воздуховод спиральный 315» после замены
 * превращалась в «Воздуховод спирально-навивной 315, м.п. 315». Размер
 * оказывался дважды, а разбор количества принимал второй «315» за
 * количество — в смете появлялось «315 штук».
 *
 * ЧТО ИМЕННО УБИРАЕМ
 *
 * Размер, который встречается В СТРОКЕ, если он же есть в названии. То
 * есть смотрим на `line`, а не на `dims` позиции: `dims` — это размеры
 * самой позиции, и они могут отличаться от того, что написал клиент
 * (менеджер мог сопоставить строку с другой позицией).
 *
 * Если в строке «315», а позиция «400», то:
 *   - «400» из названия убрать НЕЛЬЗЯ: это размер самой позиции, без него
 *     название станет неверным;
 *   - «315» из названия убрать МОЖНО: он уже есть в строке, и без него
 *     информация не теряется.
 *
 * Поэтому перебираем числа из строки, а `dims` служит лишь подсказкой,
 * какие из них действительно размеры, а не часть названия.
 */
function stripDuplicateDims(name: string, line: string, dims: number[]): string {
  /**
   * Числа из строки сметы. Ограничиваем тремя-четырьмя цифрами: диаметры
   * вентиляции — 80…1250, а артикулы и количества бывают любыми, и
   * вырезать «10» из названия «Воздуховод 10-й серии» нельзя.
   */
  const lineNumbers = new Set(
    (line.match(/\d{2,4}/g) ?? []).map((n) => Number(n)),
  );

  /**
   * Число убираем, если оно есть в строке И является размером позиции
   * либо совпадает с одним из её размеров. Второе условие не обязательно
   * (менеджер мог сопоставить строку с другой позицией), но первое —
   * да: вырезать из названия произвольное число из строки опасно.
   *
   * Ограничиваемся случаем, когда в названии есть ХОТЯ БЫ ОДИН размер
   * позиции. Иначе мы бы чистили «Тройник 315/200» от «315», если клиент
   * написал его в строке, и название потеряло бы размер.
   */
  const hasOwnDim = dims.some((d) => new RegExp(`(^|\\D)${d}(\\D|$)`).test(name));
  if (!hasOwnDim) return name;

  let result = name;
  for (const d of dims) {
    if (!lineNumbers.has(d)) continue;

    result = result.replace(
      new RegExp(`(?:[,;]\\s*|[dф]\\s*|\\s+)${d}(?=\\D|$)`, "gi"),
      "",
    );
  }

  result = result.replace(/\s+/g, " ").replace(/[\s,;]+$/, "").trim();
  /**
   * Запятые посреди названия убираем.
   *
   * Разбор CSV иногда склеивает в название единицу измерения из соседней
   * колонки: «Воздуховод спирально-навивной 315, м.п.». Когда размер из
   * названия вырезан, единица остаётся висеть посреди фразы — «Воздуховод
   * спирально-навивной, м.п.». На цену это не влияет (тип и размеры
   * разбираются отдельно), но в КП такие названия выглядят небрежно.
   *
   * Заменяем «, » на пробел, а не удаляем: «Тройник 315/200, 90°» не
   * должен превратиться в «Тройник 315/20090°».
   */
  result = result.replace(/\s*,\s*/g, " ").replace(/\s+/g, " ").trim();

  return result.length >= 3 ? result : name;
}
