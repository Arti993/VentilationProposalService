/**
 * Инструмент RAG для агента: поиск по прайсу по смыслу.
 *
 * Когда нужен: пользователь спрашивает про позицию в свободной форме —
 * «а есть у вас отвод на 90 на 250», «сколько стоит тройник 315 на 200»,
 * «почему не нашлась заглушка». Детерминированный матчер такие вопросы
 * не обслуживает, он работает только со сметой.
 *
 * Чего инструмент НЕ делает:
 *  - не ставит цены в смету. Он возвращает кандидатов с ценами из прайса,
 *    но решение о применении цены принимает человек или матчер;
 *  - не выдаёт «примерную» цену, если совпадений нет. Пустая выдача —
 *    правильный ответ, если позиции в прайсе нет.
 *
 * Защита от подмены: инструмент только читает прайс. Никаких параметров,
 * которыми можно повлиять на цену, у него нет.
 */
import { tool } from "@langchain/core/tools";
import { z } from "zod";
import { hybridSearch } from "../rag/hybrid.ts";
import { SIMILARITY_FLOOR } from "../rag/search.ts";

export function makePriceSearchTool() {
  return tool(
    async ({ query, limit }) => {
      const hits = await hybridSearch(query, { limit: limit ?? 5 });

      // Отсекаем случайные совпадения. Порог намеренно высокий: лучше
      // не найти, чем показать не тот товар — так же, как в матчере.
      const relevant = hits.filter((h) => h.vectorScore >= SIMILARITY_FLOOR);

      if (relevant.length === 0) {
        return JSON.stringify({
          found: false,
          query,
          message:
            "В прайсе нет подходящей позиции. Нельзя называть цену — " +
            "если бы она была, поиск бы её нашёл. Скажи прямо, что позиции " +
            "в прайсе нет и её нужно уточнить у менеджера.",
        });
      }

      return JSON.stringify({
        found: true,
        query,
        results: relevant.map((h) => ({
          code: h.code,
          name: h.rawName,
          price: h.price,
          similarity: Number(h.vectorScore.toFixed(3)),
        })),
        note:
          "Цены — из прайса, не придумывай свои. Похожесть < 0.8 значит, " +
          "что позиция может называться иначе: уточни, а не выдавай за точное совпадение.",
      });
    },
    {
      name: "search_price",
      description:
        "Поиск позиции в прайсе по описанию на свободном языке. " +
        "Возвращает кандидатов с ценами из прайса. Используй, когда " +
        "пользователь спрашивает про наличие или цену товара, а не про " +
        "загруженную смету. Если ничего не нашлось — позиции в прайсе нет.",
      schema: z.object({
        query: z
          .string()
          .describe("описание позиции словами пользователя, как он её назвал"),
        limit: z
          .number()
          .nullable()
          .describe("сколько кандидатов вернуть, по умолчанию 5"),
      }),
    },
  );
}
