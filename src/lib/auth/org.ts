/**
 * Постоянные идентификаторы организаций и общие правила владения.
 *
 * `org_demo` — организация, которой принадлежат демо-прайс на 215 позиций
 * и все сметы, созданные до появления аккаунтов. Она же — владелец смет
 * анонимных пользователей: работодатель должен увидеть работающий
 * продукт, не регистрируясь.
 *
 * ПОЧЕМУ ФИКСИРОВАННЫЙ ID, А НЕ ПОИСК ПО SLUG
 *
 * Значение используется в миграциях и в сравнениях на каждом запросе.
 * Поиск по slug на каждом запросе — лишний обмен с базой ради строки,
 * которая никогда не меняется. Slug нужен только человеку в адресе.
 */

/** Организация демо-данных и анонимных пользователей. */
export const DEMO_ORG_ID = "org_demo";
export const DEMO_ORG_SLUG = "demo";
export const DEMO_ORG_NAME = "Демо-прайс";

/**
 * Сколько живут сметы.
 *
 * 24 часа — для анонимов это разумно: человек посмотрел, ушёл. Но для
 * вошедшего пользователя сутки — это «моя работа пропала за ночь», и
 * ревью справедливо назвало это недостатком. Поэтому срок зависит от
 * владельца: демо-данные убираются быстро, данные организации — живут,
 * пока владелец их не удалит.
 */
export const ANON_TTL_MS = 24 * 60 * 60 * 1000;

/** Организация демо: в ней живут анонимы и старые строки. */
export function isDemoOrg(orgId: string | null | undefined): boolean {
  return orgId === DEMO_ORG_ID;
}

/**
 * Сколько дней хранить смету организации.
 *
 * 365, а не «вечно»: держать чужие коммерческие данные бессрочно — это
 * ответственность (152-ФЗ, GDPR), а не удобство. Год — разумный срок,
 * за который смета либо превратилась в сделку, либо не нужна.
 */
export const ORG_TTL_MS = 365 * 24 * 60 * 60 * 1000;

/** Срок жизни сметы для конкретного владельца. */
export function ttlFor(orgId: string | null | undefined): number {
  return isDemoOrg(orgId) ? ANON_TTL_MS : ORG_TTL_MS;
}
