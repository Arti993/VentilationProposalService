import { ProposalPage } from "@views/proposal";
import { getActor } from "@/lib/auth/guard";

export const metadata = {
  title: "Приложение — КП по смете",
  description: "Загрузите смету клиента и получите коммерческое предложение.",
};

/**
 * Страница всегда рендерится на сервере.
 *
 * `getActor` читает cookie через `headers()`. На этапе сборки заголовков
 * нет, и Next.js пытался бы отрендерить страницу статически — отсюда
 * ошибка `Dynamic server usage`. Явное `force-dynamic` убирает и ошибку,
 * и бессмысленную попытку.
 */
export const dynamic = "force-dynamic";

/**
 * Рабочий экран сервиса.
 *
 * Отделён от лендинга намеренно: у них разные задачи и разная аудитория.
 * Лендинг продаёт и показывает, приложение работает. Смешивать их на
 * одном экране — значит получить страницу, которая неудобна в работе и
 * неубедительна в продаже.
 *
 * ПОЧЕМУ ЗДЕСЬ ЧИТАЕТСЯ ПОЛЬЗОВАТЕЛЬ
 *
 * Шапке нужно знать, показывать «Войти» или «Выйти». Если узнавать это в
 * браузере, кнопка появляется через полсекунды — и человек, ищущий вход,
 * решает, что его нет. Сервер знает ответ сразу, поэтому состояние
 * приходит пропсом и попадает в первый же HTML.
 *
 * Сама проверка прав при этом НЕ опирается на это: `getActor` вернёт null
 * для гостя, а все защищённые маршруты проверяют сессию сами. Здесь это
 * только для интерфейса.
 */
export default async function AppPage() {
  const actor = await getActor();

  /**
   * Аноним — это гость с точки зрения интерфейса.
   *
   * У него есть сессия, но нет своей организации: свои прайсы недоступны.
   * Показывать ему имя и аватар бессмысленно — ему нужен путь к
   * регистрации.
   *
   * Если имя пустое (старые аккаунты, регистрация без имени), подставляем
   * почту: пустая строка на месте имени выглядит как поломка.
   */
  const user =
    actor && !actor.isAnonymous && actor.email
      ? {
          name: actor.name.trim() || actor.email,
          email: actor.email,
          image: actor.image,
        }
      : null;

  return <ProposalPage user={user} />;
}
