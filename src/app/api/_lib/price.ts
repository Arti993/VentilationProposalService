/**
 * Загрузка прайса для API-роутов.
 *
 * Прайс живёт в Postgres (таблица price_items) и принадлежит организации.
 * Здесь только тонкая обёртка, чтобы роуты не знали деталей хранения.
 *
 * ПОЧЕМУ `orgId` ОБЯЗАТЕЛЕН
 *
 * Параметр без значения по умолчанию — это защита, а не строгость. Прайс
 * с ценами конкурента или другого клиента не должен попасть в ответ
 * никому. Если бы у `getPrice` был вариант «по умолчанию», рано или
 * поздно его позвали бы в новом роуте и не заметили. Здесь забыть
 * организацию нельзя: TypeScript не пропустит.
 */
import { loadPrice } from "@/db/repositories/price.ts";
import type { PriceItem } from "@/lib/price/normalize.ts";

/**
 * Читает прайс организации из БД (с кэшем на 5 минут).
 *
 * Пустой массив — легальный ответ: у новой организации прайса ещё нет.
 * Все позиции сметы получат статус «нет в прайсе», и это правильный
 * результат: цену брать неоткуда.
 */
export async function getPrice(orgId: string): Promise<PriceItem[]> {
  return loadPrice(orgId);
}
